"""dbt: one contract, two places to enforce it.

``to_schema_yml`` turns a rowgate contract into dbt tests, so the same rules run inside
``dbt build``. ``check_model`` reads a model straight out of a dbt-duckdb database and
runs the full rowgate gate, which adds what dbt tests don't do: a quarantine frame
with a reason on every row, history across runs, and a written explanation.

    rowgate dbt contracts/orders.toml --model orders > models/orders_rowgate.yml
    dbt build
    rowgate check target/dev.duckdb --table main.orders --contract contracts/orders.toml

Range tests use ``dbt_utils``; add it to ``packages.yml``. Regex patterns have no
portable dbt test, so they're listed as comments to keep in rowgate.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..contract import Contract
from ..frames import read_duckdb
from ..pipeline import Outcome, validate


def _y(v: Any) -> str:
    return json.dumps(v, default=str)


def to_schema_yml(contract: Contract | str | Path, model: str, *, description: str | None = None) -> str:
    """dbt ``schema.yml`` text with ``data_tests`` for every rule dbt can express."""
    if not isinstance(contract, Contract):
        contract = Contract.from_toml(contract)
    lines = ["# Generated by rowgate from a data contract. Edit the contract, not this file.", "version: 2", "",
             "models:", f"  - name: {model}"]
    lines.append(f"    description: {_y(description or 'Checked by a rowgate data contract')}")
    model_tests = []
    for rule in contract.rules:
        if rule.sql:
            model_tests.append(("dbt_utils.expression_is_true", {"expression": rule.sql}, rule.name))
    if model_tests:
        lines.append("    data_tests:")
        for test, args, name in model_tests:
            lines += [f"      - {test}:", f"          name: {_y(model + '_' + name)}", "          arguments:"]
            lines += [f"            {k}: {_y(v)}" for k, v in args.items()]
    lines.append("    columns:")
    for name, col in contract.columns.items():
        lines.append(f"      - name: {name}")
        tests: list[str] = []
        if col.required:
            tests.append("          - not_null")
        if col.unique:
            tests.append("          - unique")
        if col.accepted is not None:
            tests += ["          - accepted_values:", "              arguments:",
                      f"                values: {_y(list(col.accepted))}"]
        if col.min is not None or col.max is not None:
            tests += ["          - dbt_utils.accepted_range:", "              arguments:"]
            if col.min is not None:
                tests.append(f"                min_value: {_y(col.min)}")
            if col.max is not None:
                tests.append(f"                max_value: {_y(col.max)}")
        if tests:
            lines += ["        data_tests:"] + tests
        if col.pattern is not None:
            lines.append(f"        # pattern {col.pattern} is enforced by rowgate (no portable dbt test)")
    return "\n".join(lines) + "\n"


def check_model(database: str | Path | Any, relation: str, contract: Contract | str | Path, **kw: Any) -> Outcome:
    """Run the rowgate gate on a model that dbt-duckdb built."""
    return validate(read_duckdb(database, table=relation), contract, source=f"{database}:{relation}", **kw)
